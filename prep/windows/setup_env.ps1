<#
.SYNOPSIS
  Set up Open4DGS (prep + TriGS trainer) on Windows 11 with an NVIDIA GPU, without admin rights.

.DESCRIPTION
  Re-runnable; completed steps are skipped. Creates, under -Root (default C:\o4d):
    venv\          Python 3.11 environment (PyTorch 2.10 cu128, trainer, RoMa v2, MEMFOF, ...)
    cuda-12.8\     user-local CUDA 12.8 toolkit from NVIDIA redistributables (no driver change)
    uv-cache\      uv package cache (short path avoids Windows MAX_PATH build failures)
    src\           patched fused-local-corr checkout (RoMa v2's CUDA correlation kernel)
    o4d-env.cmd    environment script: `call C:\o4d\o4d-env.cmd` before running the pipeline

  Keep -Root outside cloud-synced folders (OneDrive, Nextcloud): the environment is ~8 GB of
  small files.

  Prerequisites: NVIDIA driver supporting CUDA 12.8 (>= 570), Git, Visual Studio 2022 with the
  "Desktop development with C++" workload (CUDA 12.8 rejects the VS 2026 / MSVC 14.5x toolset),
  winget (for uv, if uv is missing).

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File prep\windows\setup_env.ps1
#>
param(
    [string]$Root = "C:\o4d",
    [string]$TrigsRepo = (Join-Path (Split-Path -Parent (Split-Path -Parent (Split-Path -Parent $PSScriptRoot))) "open4dgs-trigs"),
    [string]$CudaVersion = "12.8.1",
    [string]$CudaArch = "",
    [int]$MaxJobs = 8
)
$ErrorActionPreference = "Stop"
$CoreRepo = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$Venv = Join-Path $Root "venv"
$Py = Join-Path $Venv "Scripts\python.exe"
$CudaHome = Join-Path $Root "cuda-12.8"
$EnvCmd = Join-Path $Root "o4d-env.cmd"
$FlcCommit = "689f2f7303ca0d97ac1f3d1364c732c6d8e889a8"

function Step($msg) { Write-Host "`n=== $msg ===" -ForegroundColor Cyan }
function Invoke-InEnv([string]$cmdline) {
    # Run a command inside cmd.exe with o4d-env.cmd loaded; stop on failure.
    & cmd.exe /d /c "call `"$EnvCmd`" >nul 2>&1 && $cmdline"
    if ($LASTEXITCODE -ne 0) { throw "command failed ($LASTEXITCODE): $cmdline" }
}

if (-not (Test-Path (Join-Path $TrigsRepo "pyproject.toml"))) { throw "open4dgs-trigs checkout not found at $TrigsRepo (pass -TrigsRepo)" }
New-Item -ItemType Directory -Force $Root, (Join-Path $Root "uv-cache"), (Join-Path $Root "src") | Out-Null
$env:UV_CACHE_DIR = Join-Path $Root "uv-cache"
$env:UV_PYTHON_INSTALL_DIR = Join-Path $Root "python"

Step "Prerequisites"
$smi = (& nvidia-smi --query-gpu=name,driver_version,compute_cap --format=csv,noheader) | Select-Object -First 1
Write-Host "GPU: $smi"
if (-not $CudaArch) { $CudaArch = ($smi -split ",")[2].Trim() }
Write-Host "CUDA arch: $CudaArch"
& git --version | Out-Null
if (-not (Get-Command uv -ErrorAction SilentlyContinue)) {
    winget install --id astral-sh.uv --exact --silent --accept-package-agreements --accept-source-agreements
    $env:PATH = "$env:LOCALAPPDATA\Microsoft\WinGet\Links;$env:PATH"
}
& uv --version
$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
$vs2022 = & $vswhere -version "[17.0,18.0)" -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath | Select-Object -First 1
if (-not $vs2022) { throw "Visual Studio 2022 with C++ build tools not found (CUDA 12.8 needs MSVC 14.3x/14.4x)" }
$toolset = (Get-ChildItem (Join-Path $vs2022 "VC\Tools\MSVC") | Where-Object { $_.Name -match '^14\.[34]\d\.' } | Sort-Object Name -Descending | Select-Object -First 1).Name
if (-not $toolset) { throw "No MSVC 14.3x/14.4x toolset in $vs2022" }
$vcvarsVer = ($toolset -split '\.')[0..1] -join '.'
Write-Host "MSVC: $vs2022 toolset $toolset"

Step "Python 3.11 venv + PyTorch 2.10 (cu128)"
if (-not (Test-Path $Py)) { & uv venv --python 3.11 $Venv; if ($LASTEXITCODE) { throw "uv venv failed" } }
& $Py -c "import torch" 2>$null
if ($LASTEXITCODE -ne 0) {
    & uv pip install --python $Py --index-url https://download.pytorch.org/whl/cu128 torch==2.10.0+cu128 torchvision==0.25.0+cu128
    & uv pip install --python $Py setuptools wheel ninja numpy==2.4.4
}

Step "CUDA $CudaVersion toolkit (user-local redistributables)"
if (-not (Test-Path (Join-Path $CudaHome "bin\nvcc.exe"))) {
    & $Py -I (Join-Path $PSScriptRoot "fetch_cuda_redist.py") --version $CudaVersion --download-dir (Join-Path $Root "cuda-dl") --dest $CudaHome
    if ($LASTEXITCODE) { throw "CUDA redist fetch failed" }
}

Step "Environment script $EnvCmd"
$archNoDot = $CudaArch -replace '\.', ''
@"
@echo off
rem Generated by prep\windows\setup_env.ps1. Usage: call $EnvCmd
if not defined VSCMD_VER (
  call "$vs2022\VC\Auxiliary\Build\vcvars64.bat" -vcvars_ver=$vcvarsVer >nul
)
set "CUDA_HOME=$CudaHome"
set "CUDA_PATH=$CudaHome"
set "PATH=$CudaHome\bin;$Venv\Scripts;%PATH%"
set "TORCH_CUDA_ARCH_LIST=$CudaArch"
set "CUDA_ARCHITECTURES=$archNoDot"
set "MAX_JOBS=$MaxJobs"
set "DISTUTILS_USE_SDK=1"
set "VIRTUAL_ENV=$Venv"
set "UV_PROJECT_ENVIRONMENT=$Venv"
set "UV_CACHE_DIR=$Root\uv-cache"
set "UV_PYTHON_INSTALL_DIR=$Root\python"
set "PYTHONUTF8=1"
set "PYTHONIOENCODING=utf-8"
set "REPO=$CoreRepo"
set "OPEN4DGS_TRIGS=$TrigsRepo"
"@ | Set-Content -Path $EnvCmd -Encoding ascii

Step "TriGS trainer (builds gsplat 1.5.3 + PyTorch3D 0.7.9 for sm_$archNoDot)"
Invoke-InEnv "cd /d `"$TrigsRepo`" && uv sync --locked --inexact --python `"$Py`" --preview-features extra-build-dependencies --no-build-isolation-package pytorch3d --no-build-isolation-package gsplat"

Step "Preparation backends (RoMa v2, MEMFOF) and common packages"
Invoke-InEnv "uv pip install --python `"$Py`" `"git+https://github.com/Parskatt/RoMaV2.git@v2.0.1`" `"git+https://github.com/msu-video-group/memfof.git@a51de9fc59c6fe20ba08e079372c7b583d58a712`" pillow tqdm imageio matplotlib"

Step "fused-local-corr (RoMa v2 CUDA kernel; upstream ships Linux wheels only)"
$flc = Join-Path $Root "src\fused-local-corr"
if (-not (Test-Path $flc)) { & git clone -q https://github.com/Parskatt/fused-local-corr.git $flc }
& git -C $flc checkout -q -f $FlcCommit
& git -C $flc apply --ignore-whitespace --whitespace=nowarn (Join-Path $PSScriptRoot "fused-local-corr-msvc.patch")
if ($LASTEXITCODE) { throw "patch failed" }
Invoke-InEnv "uv pip install --python `"$Py`" --no-build-isolation --reinstall-package fused-local-corr `"$flc`""

Step "Smoke tests"
Invoke-InEnv "python `"$PSScriptRoot\smoke_test.py`""
Write-Host "`nDone. Open a cmd prompt and run:  call $EnvCmd" -ForegroundColor Green
